HAS_NODE = shutil.which("node") is not None and (ROOT / "codegraph/plugins/ts/extractor/node_modules/typescript").exists()


def write(root: Path, files: dict) -> Path:
    for rel, body in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(body).lstrip("\n"))
    return root


def classify(tmp: Path, files: dict, cfg: dict | None = None, include: bool = False) -> G.Classifier:
    root = write(tmp / "p", files)
    clf = G.Classifier(root, cfg, include=include)
    C.scan_tree(root, classifier=clf)
    return clf


def reason(clf: G.Classifier, rel: str):
    h = clf.lookup(rel)
    return (h["kind"], h["reason"]) if h else None


def cg(*args):
    return subprocess.run([sys.executable, "-m", "codegraph.cli", *map(str, args)], cwd=ROOT, capture_output=True, text=True)


