def test_default_index_has_no_generated_nodes_and_coverage_lists_them(tmp_path):
    root = write(tmp_path / "py", PY_APP)
    st = GraphStore(tmp_path / "py.db") if index_project(root, tmp_path / "py.db", "py") else None
    files = {r["file"] for r in st.q("SELECT DISTINCT file FROM nodes WHERE file IS NOT NULL")}
    assert "shop/service.py" in files and "shop/api.py" in files
    assert not files & {"shop/orders_pb2.py", "shop/schema.py"}
    callers = {c["fqn"] for c in Q.impact(st, "shop.service.place")["callers"]}
    assert callers == {"shop.api.create"}
    cov = C.for_graph(st)["py"]
    g = cov["generated"]
    assert g["mode"] == "excluded" and g["files"] == 2
    assert g["by_reason"] == {"protoc output (Python)": 1, "'Code generated ... DO NOT EDIT.' header": 1}
    py = next(e for e in cov["languages"] if e["language"] == "python")
    assert py["files"] == 3 and py.get("files_complete") is not False      # the 2 generated files are not "discovered"
    text = C.render(C.for_graph(st))
    assert "generated: 2 files excluded" in text and "shop/orders_pb2.py" in text
    assert "generated: 2 files excluded" in C.summary_line(cov)


def test_include_generated_labels_every_node(tmp_path):
    root = write(tmp_path / "py", PY_APP)
    stats = index_project(root, tmp_path / "py.db", "py", include_generated=True)
    assert stats["generated"]["mode"] == "indexed" and stats["generated"]["nodes_labelled"] > 0
    st = GraphStore(tmp_path / "py.db")
    rows = st.q("SELECT id, file, attrs FROM nodes WHERE file IN ('shop/orders_pb2.py', 'shop/schema.py')")
    assert rows and all(json.loads(r["attrs"])["generated"]["kind"] == "generated" for r in rows)
    assert not [r for r in st.q("SELECT attrs FROM nodes WHERE file = 'shop/service.py'") if r["attrs"] and "generated" in r["attrs"]]
    imp = Q.impact(st, "shop.service.place")
    by = {c["fqn"]: c for c in imp["callers"]}
    assert set(by) == {"shop.api.create", "shop.orders_pb2.decode", "shop.schema.run"}
    assert Q.caller_label(by["shop.orders_pb2.decode"]) == "  [generated: protoc output (Python)]"
    assert Q.caller_label(by["shop.api.create"]) == ""
    assert C.for_graph(st)["py"]["generated"]["mode"] == "indexed"
    out = cg("impact", "shop.service.place", "--db", tmp_path / "py.db").stdout
    assert "shop.schema.run  [generated: 'Code generated ... DO NOT EDIT.' header]" in out


