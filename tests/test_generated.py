def test_gitattributes_patterns_follow_git():
    rules = G.parse_gitattributes("Api.elm linguist-generated\n/root.ts linguist-generated\nsrc/*.ts linguist-vendored\n"
                                  "docs/ linguist-generated\n\"quoted name\" linguist-generated\n")
    rx = {r.pattern: (k, v) for r, k, v in rules}
    assert len(rules) == 3          # the directory and the quoted pattern are not file patterns
    m = lambda p: [k for r, k, v in rules if r.match(p)]       # noqa: E731
    assert m("Api.elm") == m("a/b/Api.elm") == ["generated"]
    assert m("root.ts") == ["generated"] and m("a/root.ts") == []
    assert m("src/x.ts") == ["vendored"] and m("src/a/x.ts") == []
    assert rx


