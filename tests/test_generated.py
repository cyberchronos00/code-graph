    assert reason(clf, "src/api/generated/deep/x.ts") == ("generated", "linguist-generated (.gitattributes)")
    assert clf.lookup("src/api/generated/custom.ts") is None
    assert reason(clf, "third_party/lib/a.c") == ("vendored", "linguist-vendored (.gitattributes)")
    assert reason(clf, "public/vendor.min.js") == ("generated", "linguist-generated (.gitattributes)")
    assert clf.lookup("src/legacy.ts") is None
    assert clf.lookup("src/app.ts") is None


