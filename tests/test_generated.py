def test_config_rules_and_validation(tmp_path):
    cfg = CFG.parse({"generated": {"paths": ["src/gen/**"], "vendored": ["libs/**"], "keep": ["src/gen/hand.ts", "src/x_pb2.py"],
                                   "include": False}})
    clf = classify(tmp_path, {"src/gen/a.ts": "x\n", "src/gen/hand.ts": "x\n", "libs/z.js": "x\n", "src/x_pb2.py": "x = 1\n"}, cfg)
