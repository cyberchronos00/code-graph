@pytest.mark.parametrize("cfgfile,body", [
    ("capacitor.config.ts", "import { CapacitorConfig } from '@capacitor/cli';\n"
                            "const config: CapacitorConfig = { appId: 'com.example.app', appName: 'Example', webDir: 'dist' };\n"
                            "export default config;\n"),
    ("capacitor.config.js", "module.exports = { appId: 'com.example.app', webDir: \"dist\" }\n"),
    ("capacitor.config.json", '{"appId": "com.example.app", "webDir": "dist"}\n'),
])
def test_capacitor_web_dir_and_copy_targets(tmp_path, cfgfile, body):
    clf = classify(tmp_path, {
        cfgfile: body,
        "src/battery.ts": "export const b = 1\n",
        "android/app/src/main/assets/public/assets/index-abc.js": "x\n",
        "android/app/src/main/assets/public/index.html": "<html></html>\n",
        "android/app/src/main/assets/capacitor.config.json": "{}\n",
        "android/app/src/main/java/com/example/app/MainActivity.java": "class MainActivity {}\n",
        "android/capacitor-cordova-android-plugins/src/main/java/X.java": "class X {}\n",
        "ios/App/App/public/assets/index-abc.js": "x\n",
        "ios/App/App/AppDelegate.swift": "class AppDelegate {}\n",
    })
    h = clf.lookup("android/app/src/main/assets/public/assets/index-abc.js")
    assert h == {"kind": "copied", "reason": "copy of dist/ (Capacitor webDir)", "copy_of": "dist/assets/index-abc.js"}
    assert clf.lookup("ios/App/App/public/assets/index-abc.js")["copy_of"] == "dist/assets/index-abc.js"
    assert reason(clf, "android/app/src/main/assets/capacitor.config.json") == ("generated", "Capacitor sync output")
    assert reason(clf, "android/capacitor-cordova-android-plugins/src/main/java/X.java") == ("generated", "Capacitor sync output")
    # the native app's own code and the web sources are not copies
    for rel in ("src/battery.ts", "android/app/src/main/java/com/example/app/MainActivity.java", "ios/App/App/AppDelegate.swift"):
        assert clf.lookup(rel) is None, rel
    g = clf.summary()
    assert {c["target"]: c["source"] for c in g["copies"]}["android/app/src/main/assets/public"] == "dist"
    assert g["by_reason"]["copy of dist/ (Capacitor webDir)"] == 2      # source files only (the .js copies)


